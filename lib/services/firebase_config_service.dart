import 'dart:convert';
import '../models/activity_model.dart';
import '../models/lesson_model.dart';

/// Centralized Firebase Configuration Service for student-facing HTML modules.
///
/// Serves as the single source of truth for the shared Firebase Web SDK configuration
/// (`online-classes-database-70d53`) and generates the standalone `firebase.js` runtime script.
class FirebaseConfigService {
  static const String firebaseSdkVersion = '10.8.0';

  static const String defaultProjectId = 'online-classes-database-70d53';
  static const String defaultAuthDomain = 'online-classes-database-70d53.firebaseapp.com';
  static const String defaultStorageBucket = 'online-classes-database-70d53.firebasestorage.app';
  static const String defaultMessagingSenderId = '';
  static const String defaultAppId = '';
  static const String defaultApiKey = '';

  final String apiKey;
  final String authDomain;
  final String projectId;
  final String storageBucket;
  final String messagingSenderId;
  final String appId;

  const FirebaseConfigService({
    this.apiKey = defaultApiKey,
    this.authDomain = defaultAuthDomain,
    this.projectId = defaultProjectId,
    this.storageBucket = defaultStorageBucket,
    this.messagingSenderId = defaultMessagingSenderId,
    this.appId = defaultAppId,
  });

  /// Generates the standalone `firebase.js` file for a generated module.
  String generateFirebaseJs({
    required String moduleId,
    required LessonModel lesson,
  }) {
    final Map<String, dynamic> configMap = {
      'apiKey': apiKey,
      'authDomain': authDomain.isNotEmpty ? authDomain : '$projectId.firebaseapp.com',
      'projectId': projectId,
      'storageBucket': storageBucket.isNotEmpty ? storageBucket : '$projectId.firebasestorage.app',
      'messagingSenderId': messagingSenderId,
      'appId': appId,
    };

    final Map<String, dynamic> moduleMeta = {
      'title': lesson.title.trim().isEmpty ? 'Self-Learning Module' : lesson.title.trim(),
      'subject': lesson.subject.trim().isEmpty ? 'General Subject' : lesson.subject.trim(),
      'gradeLevel': lesson.gradeLevel.trim().isEmpty ? 'Grade 11' : lesson.gradeLevel.trim(),
    };

    // Auto-grading metadata map for clientAutoScore (only automatic grading mode & provided/inferred answers)
    final Map<String, dynamic> autoGradingMeta = {};
    for (final act in lesson.activities) {
      if (act.gradingMode == GradingMode.automatic) {
        final Map<String, dynamic> qMap = {};
        for (final q in act.questions) {
          if (q.answerStatus == AnswerStatus.provided || q.answerStatus == AnswerStatus.inferredHighConfidence) {
            qMap[q.id] = {
              'answerStatus': q.answerStatus.name,
              'correctAnswer': q.correctAnswer,
              'points': 1,
            };
          }
        }
        if (qMap.isNotEmpty) {
          autoGradingMeta[act.id] = {
            'gradingMode': 'automatic',
            'questions': qMap,
          };
        }
      }
    }

    final String configJson = jsonEncode(configMap);
    final String moduleMetaJson = jsonEncode(moduleMeta);
    final String autoGradingMetaJson = jsonEncode(autoGradingMeta);
    final String safeModuleIdJson = jsonEncode(moduleId);

    return '''
// Generated by Self-Learning Module Studio
// Firebase Modular JS SDK Integration
// Module ID: $moduleId

import { initializeApp } from "https://www.gstatic.com/firebasejs/$firebaseSdkVersion/firebase-app.js";
import { getAuth, signInAnonymously, onAuthStateChanged } from "https://www.gstatic.com/firebasejs/$firebaseSdkVersion/firebase-auth.js";
import { getFirestore, doc, getDoc, setDoc, updateDoc, serverTimestamp } from "https://www.gstatic.com/firebasejs/$firebaseSdkVersion/firebase-firestore.js";

const FIREBASE_CONFIG = $configJson;
const MODULE_ID = $safeModuleIdJson;
const MODULE_META = $moduleMetaJson;
const AUTO_GRADING_META = $autoGradingMetaJson;

(function() {
  function updateStatus(text, cssClass) {
    const badge = document.getElementById('cloud-status-badge');
    if (badge) {
      badge.textContent = text;
      badge.className = 'cloud-status-badge ' + (cssClass || '');
    }
  }

  // Local File Preview (file://) Protection
  if (window.location.protocol === 'file:') {
    console.log('Running in local file preview mode (file://). Firebase cloud saving is disabled.');
    window.ModuleFirebase = {
      isLocalPreview: true,
      currentUserUid: function() { return null; },
      saveDraft: function() { return Promise.resolve(); },
      debouncedSaveDraft: function() {},
      submitModule: function() {
        return Promise.resolve({ success: true, isPreview: true });
      }
    };

    document.addEventListener('DOMContentLoaded', function() {
      updateStatus('Preview mode — cloud saving is unavailable', 'status-preview');
    });
    return;
  }

  // Hosted Mode (HTTP / HTTPS)
  let app, auth, db;
  let currentUid = null;
  let saveDebounceTimer = null;

  async function initFirebase() {
    updateStatus('Connecting...', 'status-connecting');
    try {
      app = initializeApp(FIREBASE_CONFIG);
      auth = getAuth(app);
      db = getFirestore(app);

      onAuthStateChanged(auth, async function(user) {
        if (user) {
          currentUid = user.uid;
          updateStatus('Connected', 'status-connected');
          await loadExistingSubmission();
        } else {
          try {
            const cred = await signInAnonymously(auth);
            currentUid = cred.user.uid;
            updateStatus('Connected', 'status-connected');
            await loadExistingSubmission();
          } catch (authErr) {
            console.error('Firebase Anonymous Auth error:', authErr);
            updateStatus('Cloud saving is not available. Anonymous Firebase Authentication may not be enabled.', 'status-error');
          }
        }
      });
    } catch (err) {
      console.error('Firebase Initialization failed:', err);
      updateStatus('Cloud saving unavailable', 'status-error');
    }
  }

  function getSubmissionRef(uid) {
    const targetUid = uid || currentUid;
    return doc(db, 'modules', MODULE_ID, 'submissions', targetUid);
  }

  function computeClientAutoScore(responses) {
    let earned = 0;
    let possible = 0;

    for (const actId in AUTO_GRADING_META) {
      const actData = AUTO_GRADING_META[actId];
      if (!actData || actData.gradingMode !== 'automatic') continue;

      const actResponses = responses[actId] || {};
      const questionsMap = actData.questions || {};

      for (const qId in questionsMap) {
        const qMeta = questionsMap[qId];
        // Only automatically score questions where answerStatus is provided or inferredHighConfidence
        if (qMeta.answerStatus !== 'provided' && qMeta.answerStatus !== 'inferredHighConfidence') {
          continue;
        }

        const pts = qMeta.points || 1;
        possible += pts;

        const studentAns = (actResponses[qId] || '').toString().trim().toLowerCase();
        const expectedAns = (qMeta.correctAnswer || '').toString().trim().toLowerCase();

        if (studentAns !== '' && studentAns === expectedAns) {
          earned += pts;
        }
      }
    }

    return { earned: earned, possible: possible };
  }

  function gatherData(status) {
    const firstName = (document.getElementById('firstName')?.value || '').trim();
    const surname = (document.getElementById('surname')?.value || '').trim();
    const middleName = (document.getElementById('middleName')?.value || '').trim();
    const gradeLevel = (document.getElementById('gradeLevel')?.value || '').trim();
    const section = (document.getElementById('section')?.value || '').trim();
    const lrn = (document.getElementById('lrn')?.value || '').trim();

    const responses = {};
    document.querySelectorAll('.activity-card[data-activity-id]').forEach(function(actEl) {
      const actId = actEl.getAttribute('data-activity-id');
      responses[actId] = {};

      actEl.querySelectorAll('.question-item[data-question-id]').forEach(function(qEl) {
        const qId = qEl.getAttribute('data-question-id');

        const checkedRadio = qEl.querySelector('input[type="radio"]:checked');
        if (checkedRadio) {
          responses[actId][qId] = checkedRadio.value;
        } else {
          const textInput = qEl.querySelector('textarea, input[type="text"]');
          if (textInput) {
            responses[actId][qId] = textInput.value;
          }
        }
      });
    });

    const autoScore = computeClientAutoScore(responses);

    return {
      schemaVersion: 1,
      moduleId: MODULE_ID,
      module: MODULE_META,
      authUid: currentUid,
      student: {
        firstName: firstName,
        surname: surname,
        middleName: middleName,
        gradeLevel: gradeLevel,
        section: section,
        lrn: lrn
      },
      responses: responses,
      status: status || 'draft',
      clientAutoScore: autoScore,
      updatedAt: serverTimestamp()
    };
  }

  async function saveDraft() {
    if (!currentUid || !db) return;
    updateStatus('Saving...', 'status-saving');
    try {
      const data = gatherData('draft');
      const ref = getSubmissionRef(currentUid);
      const snap = await getDoc(ref);

      if (!snap.exists()) {
        data.createdAt = serverTimestamp();
        data.submittedAt = null;
        await setDoc(ref, data);
      } else {
        const existing = snap.data();
        if (existing && existing.status === 'submitted') {
          updateStatus('Previously submitted.', 'status-submitted');
          return;
        }
        await updateDoc(ref, data);
      }
      updateStatus('Saved', 'status-saved');
    } catch (err) {
      console.error('Save draft failed:', err);
      updateStatus('Changes are waiting to be saved.', 'status-offline');
    }
  }

  function debouncedSaveDraft() {
    if (saveDebounceTimer) clearTimeout(saveDebounceTimer);
    saveDebounceTimer = setTimeout(saveDraft, 1000);
  }

  async function submitModule() {
    if (!currentUid || !db) {
      throw new Error('Cloud saving is unavailable. Check your connection.');
    }
    updateStatus('Saving...', 'status-saving');
    const data = gatherData('submitted');
    data.submittedAt = serverTimestamp();

    const ref = getSubmissionRef(currentUid);
    const snap = await getDoc(ref);

    if (!snap.exists()) {
      data.createdAt = serverTimestamp();
      await setDoc(ref, data);
    } else {
      await updateDoc(ref, data);
    }
    updateStatus('Submitted', 'status-submitted');
  }

  async function loadExistingSubmission() {
    if (!currentUid || !db) return;
    try {
      const ref = getSubmissionRef(currentUid);
      const snap = await getDoc(ref);
      if (snap.exists()) {
        const data = snap.data();
        restoreSubmissionData(data);
      }
    } catch (err) {
      console.error('Failed to restore submission:', err);
    }
  }

  function restoreSubmissionData(data) {
    if (!data) return;

    if (data.student) {
      if (data.student.firstName && document.getElementById('firstName')) {
        document.getElementById('firstName').value = data.student.firstName;
      }
      if (data.student.surname && document.getElementById('surname')) {
        document.getElementById('surname').value = data.student.surname;
      }
      if (data.student.middleName && document.getElementById('middleName')) {
        document.getElementById('middleName').value = data.student.middleName;
      }
      if (data.student.gradeLevel && document.getElementById('gradeLevel')) {
        document.getElementById('gradeLevel').value = data.student.gradeLevel;
        document.getElementById('gradeLevel').dispatchEvent(new Event('change'));
      }
      if (data.student.section && document.getElementById('section')) {
        document.getElementById('section').value = data.student.section;
      }
      if (data.student.lrn && document.getElementById('lrn')) {
        document.getElementById('lrn').value = data.student.lrn;
      }
    }

    const lessonSection = document.getElementById('lesson-content-section');
    const studentFormSection = document.getElementById('student-form-section');

    if (data.student && data.student.firstName && data.student.surname && data.student.gradeLevel && data.student.section) {
      if (lessonSection) lessonSection.classList.remove('locked');
      if (studentFormSection) studentFormSection.style.display = 'none';
    }

    if (data.responses) {
      for (const actId in data.responses) {
        const qMap = data.responses[actId] || {};
        for (const qId in qMap) {
          const val = qMap[qId];
          const qContainer = document.querySelector('.question-item[data-question-id="' + qId + '"]');
          if (qContainer) {
            const radio = qContainer.querySelector('input[type="radio"][value="' + CSS.escape(val) + '"]');
            if (radio) {
              radio.checked = true;
            } else {
              const textInput = qContainer.querySelector('textarea, input[type="text"]');
              if (textInput) {
                textInput.value = val;
              }
            }
          }
        }
      }
    }

    if (data.status === 'submitted') {
      updateStatus('Previously submitted.', 'status-submitted');
      const banner = document.getElementById('submission-status-banner');
      if (banner) {
        banner.style.display = 'block';
        banner.textContent = 'Your activities were previously submitted successfully.';
      }
    }
  }

  window.ModuleFirebase = {
    isLocalPreview: false,
    currentUserUid: function() { return currentUid; },
    saveDraft: saveDraft,
    debouncedSaveDraft: debouncedSaveDraft,
    submitModule: submitModule
  };

  document.addEventListener('DOMContentLoaded', initFirebase);
})();
''';
  }
}
